def test_mastery_rules(stored):
    with pytest.raises(pipeline.AnalysisError) as e:
        progress.set_mastery("u1", "abc-C", "C:1:t2", True)
    assert e.value.status == 409 and [m["id"] for m in e.value.detail["missing"]] == ["C:1:t0", "C:1:t1"]
    s = progress.set_mastery("u1", "abc-C", "C:1:t0", True)
    assert s["next_up"] == "C:1:t1"
    s = progress.set_mastery("u1", "abc-C", "C:1:t2", True, force=True)               # 'I know this and everything before it'
    assert set(s["mastered"]) == {"C:1:t0", "C:1:t1", "C:1:t2"}
    s = progress.set_mastery("u1", "abc-C", "C:1:t0", False)                           # un-master cascades to dependants
    assert s["mastered"] == [] and progress.saved("u1", "abc-C") == []
    with pytest.raises(pipeline.AnalysisError):
        progress.saved("../etc", "abc-C")


def test_model_failure_uses_fallback_edges(monkeypatch):
    import app.ml.infer as infer
    monkeypatch.setattr(infer, "score_pairs", lambda *a, **k: (_ for _ in ()).throw(RuntimeError("boom")))
    monkeypatch.setattr(fallback, "_call", lambda prompt, schema: {"edges": [{"before": 0, "after": 1}, {"before": 1, "after": 0}, {"before": 3, "after": 4}]})
    out = pipeline.edges_for(TOPICS, CTX, "Discrete Maths")
    assert [(i, j) for i, j, _, _ in out] == [(0, 1), (3, 4)]                         # cycle dropped
    assert all(b == "accepted" for *_, b in out)


def test_model_and_fallback_failure_uses_neighbour_rule(monkeypatch):
    import app.ml.infer as infer
    monkeypatch.setattr(infer, "score_pairs", lambda *a, **k: (_ for _ in ()).throw(RuntimeError("boom")))
