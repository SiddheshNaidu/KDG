def test_background_printed_row_when_no_key(monkeypatch):
    monkeypatch.setattr(fallback, "_key", lambda: (_ for _ in ()).throw(fallback.FallbackUnavailable("no key")))
    bg = pipeline.background_for("X", TOPICS, ["Linear Algebra, Probability"])
    assert [b["name"] for b in bg] == ["Linear Algebra", "Probability"]
    assert pipeline.background_for("X", TOPICS, ["None"]) == []


def test_background_from_fallback_resolves_topic_ids(monkeypatch):
    monkeypatch.setattr(fallback, "_call", lambda p, s: {"missing_prerequisites": [{"name": "Logic", "reason": "r", "needed_for": ["sets", "Trees"]}]})
    bg = pipeline.background_for("X", TOPICS, [])
    assert bg[0]["needed_for"] == [{"id": "C:1:t0", "name": "Sets"}, {"id": "C:1:t4", "name": "Trees"}]


def test_payload_never_names_generator(stored):
    text = json.dumps(stored).lower()
    assert not any(w in text for w in BANNED)
    assert {"nodes", "edges", "study_flow", "bottlenecks", "missing_prerequisites", "needs_subject", "analysis_id"} <= set(stored)


