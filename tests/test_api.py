from app.services import graph_ops, pipeline, progress, fallback

TOPICS = [dict(id=f"C:1:t{i}", name=n, module=1 if i < 3 else 2, module_title="M") for i, n in
          enumerate(["Sets", "Relations", "Functions", "Graphs", "Trees"])]
CTX = dict(title="Discrete Maths", module_names={1: "Basics", 2: "Graphs"})
BANNED = ("gemini", "xgboost", "fallback", "generated by", "llm", "openai", "nep6")


def edges(*pairs, band="accepted"):
    return [dict(source=f"C:1:t{a}", target=f"C:1:t{b}", confidence=0.5, band=band) for a, b in pairs]


def test_kahn_levels_and_states():
    ids = [t["id"] for t in TOPICS]
    E = edges((0, 1), (1, 2), (0, 3)) + edges((3, 4), band="uncertain")
    order, level = graph_ops.kahn(ids, graph_ops.blocking(E))
    assert order[0] == "C:1:t0" and level["C:1:t2"] == 2 and level["C:1:t4"] == 0      # uncertain edge never orders/blocks
    st = graph_ops.node_states(ids, E, {"C:1:t0"})
    assert st["C:1:t1"]["state"] == "ready" and st["C:1:t2"]["state"] == "blocked" and st["C:1:t4"]["is_start"]
    miss, pct, total = graph_ops.missing_for("C:1:t2", ids, E, set())
    assert miss == ["C:1:t0", "C:1:t1"] and total == 2 and pct == 0.0


